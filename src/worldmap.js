// the hero's portfolio map. Built once from Natural Earth's 1:50m land
// (public domain, via the world-atlas package) and kept here as a bitmap, so
// the page needs no map library: '1' is a land dot.
//
// Projection: longitude -100 to 42 and latitude 12 to 60, equirectangular
// with longitude scaled by cos 36 degrees; one cell is 1.3 units (about
// 1.3 degrees of latitude) and the board is 88 x 36 cells.
export const MAP = { lon0: -100, lon1: 42, lat0: 12, lat1: 60, k: Math.cos(36 * Math.PI / 180), cell: 1.3, cols: 88, rows: 36 }
export const MAP_W = MAP.cols * MAP.cell
export const MAP_H = MAP.rows * MAP.cell
// board position of a place, in the same units as the dot grid
export const project = (lat, lon) => [(lon - MAP.lon0) * MAP.k, MAP.lat1 - lat]
